// HappyUI build: zero dependencies, just Node 18+.
//   node scripts/build.mjs
// 1. joins src/*.css (in order) into dist/happyui.css
// 2. writes a minified copy to dist/happyui.min.css
// 3. copies js/happyui.js to dist/happyui.js
// 4. reads src/tokens.css and writes tokens/tokens.json

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

// Order matters: tokens first, tones last (a tone must win).
export const ORDER = [
  "src/tokens.css",
  "src/base.css",
  "src/typography.css",
  "src/layout.css",
  "src/motion.css",
  "src/components/button.css",
  "src/components/badge.css",
  "src/components/ink.css",
  "src/components/paper.css",
  "src/components/annotation.css",
  "src/components/form.css",
  "src/components/navigation.css",
  "src/components/feedback.css",
  "src/components/data.css",
  "src/tones.css",
];

const banner = `/*! HappyUI v${pkg.version} | ${pkg.homepage} | MIT License */\n`;

function read(rel) {
  return readFileSync(join(root, rel), "utf8").replace(/\r\n/g, "\n");
}

// A small, safe minifier: keeps strings intact, drops comments and
// whitespace only where CSS does not need it. It never removes the space
// before a colon, because ".a :hover" and ".a:hover" mean different things.
export function minify(css) {
  let out = "";
  let i = 0;
  while (i < css.length) {
    const ch = css[i];
    if (ch === '"' || ch === "'") {
      let j = i + 1;
      while (j < css.length && css[j] !== ch) j += css[j] === "\\" ? 2 : 1;
      out += css.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    if (ch === "/" && css[i + 1] === "*") {
      const end = css.indexOf("*/", i + 2);
      const comment = css.slice(i, end + 2);
      if (comment.startsWith("/*!")) out += comment + "\n";
      i = end + 2;
      continue;
    }
    if (/\s/.test(ch)) {
      while (i < css.length && /\s/.test(css[i])) i++;
      const prev = out[out.length - 1];
      const next = css[i];
      const tight = "{};,>";
      if (prev === undefined || tight.includes(prev) || prev === ":" || prev === "\n" || tight.includes(next)) continue;
      out += " ";
      continue;
    }
    if (ch === "}" && out.endsWith(";")) out = out.slice(0, -1);
    out += ch;
    i++;
  }
  return out.trim() + "\n";
}

// Reads "--hui-name: value;" lines and groups them by block.
export function readTokens(css) {
  const groups = { base: {}, light: {}, dark: {}, derived: {} };
  let current = null;
  const lines = css.split("\n");
  for (let n = 0; n < lines.length; n++) {
    const line = lines[n].trim();
    if (line === ":root {") current = "base";
    else if (line === ':root,' && lines[n + 1].trim() === '[data-theme="light"] {') current = "light";
    else if (line === '[data-theme="dark"] {') current = "dark";
    else if (line === ":root," && lines[n + 1].trim() === "[data-theme] {") current = "derived";
    else if (line === "}") current = null;
    const m = line.match(/^(--hui-[a-z0-9-]+):\s*(.+);$/);
    if (current && m) groups[current][m[1]] = m[2];
  }
  return groups;
}

export function build() {
  const parts = ORDER.map((rel) => `/* ${rel} */\n${read(rel)}`);
  const css = banner + parts.join("\n");
  mkdirSync(join(root, "dist"), { recursive: true });
  writeFileSync(join(root, "dist/happyui.css"), css);
  writeFileSync(join(root, "dist/happyui.min.css"), minify(css));
  writeFileSync(join(root, "dist/happyui.js"), read("js/happyui.js"));

  const tokens = readTokens(read("src/tokens.css"));
  mkdirSync(join(root, "tokens"), { recursive: true });
  writeFileSync(
    join(root, "tokens/tokens.json"),
    JSON.stringify({ $comment: "Generated by scripts/build.mjs from src/tokens.css. Do not edit by hand.", version: pkg.version, ...tokens }, null, 2) + "\n",
  );

  const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(1) + " KB";
  console.log(`dist/happyui.css      ${kb(css)}`);
  console.log(`dist/happyui.min.css  ${kb(minify(css))}`);
  console.log(`tokens/tokens.json    ${Object.values(tokens).reduce((a, g) => a + Object.keys(g).length, 0)} tokens`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) build();
